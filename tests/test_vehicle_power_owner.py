"""Exercise actual Lua 5.1 power requests and the irreversible owner cutover."""
from test_display_startup import runtime

sim = runtime()
sim.execute('''
local Adapter = dofile(SCRIPT_ROOT..'Systems/Vehicle_Power_Adapter.lua')
local adapter = Adapter.new()
assert(not adapter:update(1,1,1,1))
get_param_handle('EFM_POWER_OWNER'):set(1)
get_param_handle('APU_POWER'):set(1)
get_param_handle('APU_RPM_STATE'):set(4)
get_param_handle('L_GEN_POWER'):set(1)
get_param_handle('R_GEN_POWER'):set(0)
get_param_handle('MAIN_POWER'):set(1)
assert(adapter:update(1,1,0,1))
assert(adapter.apu_power==1 and adapter.apu_rpm==4 and adapter.main==1)
assert(get_param_handle('F22_POWER_REQUEST_VALID'):get()==1)
assert(get_param_handle('F22_R_GEN_REQUEST'):get()==0)
get_param_handle('EFM_POWER_OWNER'):set(0)
assert(adapter:update(0,0,0,0),'owner loss started a second integrator')
assert(get_param_handle('F22_BATTERY_REQUEST'):get()==0)

-- The actual engine device must not drain/recharge or overwrite EFM outputs.
get_param_handle('EFM_POWER_OWNER'):set(1)
get_param_handle('F22_BATTERY_SOC'):set(.42)
get_param_handle('F22_DC_VOLTS'):set(26)
get_param_handle('BATTERY_POWER'):set(1)
dofile(SCRIPT_ROOT..'Systems/Engine_System.lua')
post_initialize()
for index=1,5000 do update() end
assert(get_param_handle('F22_BATTERY_SOC'):get()==.42)
assert(get_param_handle('F22_DC_VOLTS'):get()==26)
assert(get_param_handle('R_GEN_POWER'):get()==0)
assert(get_param_handle('F22_BATTERY_REQUEST'):get()==1)
get_param_handle('MAIN_POWER'):set(0)
get_param_handle('BATTERY_POWER'):set(0)
update()
assert(get_param_handle('MAIN_POWER'):get()==0 and get_param_handle('BATTERY_POWER'):get()==0)
SetCommand(10019,1); SetCommand(10019,1); update()
assert(get_param_handle('F22_PARK_REQUEST'):get()==1)
SetCommand(10019,0); update()
assert(get_param_handle('F22_PARK_REQUEST'):get()==0)
''')
print('Vehicle power: Lua requests, EFM supply authority, latched handoff, no duplicate battery/APU integration PASS')
