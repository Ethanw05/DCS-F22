h:command(10153,1);h:command(10153,0);h:step(.02);assert(h.parameters.TAXI_SWITCH==0,"momentary light release")
h:command(3003,.4);h:command(3007,5);h:step(.02)
assert(h.parameters.NAV_LIGHT_SWITCH==.4 and h.parameters.FORM_KNOB==1,"bounded direct controls")
h:command(10512);h:step(.02);assert(h.parameters.F22_EXTERNAL_LIGHTS_MASTER==0)
