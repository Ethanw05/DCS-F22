local root=assert(arg[1]);local Host=dofile(root.."/tests/lua/host.lua")
local h=Host.New(root);h:load("Cockpit/Scripts/Systems/Electrical_System.lua");h.env.post_initialize()
h:command(3001,1);h:command(3001,1);h:step(.02)
assert(h.parameters.AAR==1 and #h.commands==1,"idempotent clickable refuel command")
h:command(155);h:step(.02);assert(h.parameters.AAR==1,"own native echo ignored")
h:command(155);h:step(.02);assert(h.parameters.AAR==0,"external native toggle synchronized")
h:command(10015,1);h:command(155);h:step(.02);assert(h.parameters.AAR_READY==0)
h.draws[22]=1;h:step(.02);assert(h.parameters.AAR_READY==1,"achieved door gates ready")
